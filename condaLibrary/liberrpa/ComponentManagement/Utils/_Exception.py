class ComponentManagementError(Exception):
    def __init__(
        self,
        code: str,
        message: str,
        details: dict[str, object] | None = None,
    ) -> None:
        super().__init__(message)

        self.code: str = code
        self.message: str = message
        self.details: dict[str, object] | None = details

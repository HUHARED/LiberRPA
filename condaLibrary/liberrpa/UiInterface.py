_WAIT_RETRY_INTERVAL = 200


def _decrease_timeout_with_retry_delay(timeout: int, timeStart: float) -> int:
    timeUsed = int((monotonic() - timeStart) * 1000)
    timeout -= timeUsed

    if timeout <= 0:
        return timeout

    retryDelay = min(_WAIT_RETRY_INTERVAL, timeout)
    delay(retryDelay)
    timeout -= retryDelay

    return timeout



def _get_check_state(
    selector: SelectorUia | SelectorHtml,
    preDelay: int = 300,
    postDelay: int = 200,
) -> Literal["checked", "unchecked", "indeterminate"]:

    if selector.get("category") != "html" and selector.get("category") != "uia":
        raise UiOperationError("Can only get check state for html and uia non window elements which support check.")

    uiTarget, dictTarget = _UiElement.get_element_with_pre_delay(selector=selector, preDelay=preDelay)

    strReturn: str = ""

    if isinstance(uiTarget, uiautomation.Control):
        pattern = cast(
            uiautomation.TogglePattern | None,
            uiTarget.GetPattern(uiautomation.PatternId.TogglePattern),
        )

        if pattern is not None:
            intState: int = pattern.ToggleState
            if intState == 0:
                strReturn = "unchecked"
            elif intState == 1:
                strReturn = "checked"
            else:
                # intState == 2
                strReturn = "indeterminate"

            delay(postDelay)
            return strReturn

        raise UiOperationError(
            f"The element does not support getting check state or LiberRPA does not have permission. selector: {selector}"
        )
    else:
        # html
        if dictTarget.get("checked") == "false":
            strReturn = "unchecked"
        elif dictTarget.get("checked") == "true":
            strReturn = "checked"
        elif dictTarget.get("checked") == "indeterminate":
            strReturn = "indeterminate"
        else:
            raise UiOperationError(f"The element does not have the 'checked' attribute. selector: {selector}")

        delay(postDelay)
        return strReturn



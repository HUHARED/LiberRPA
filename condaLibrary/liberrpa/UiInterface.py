def _get_control_text_recursive(control: uiautomation.Control) -> list[str]:
    listText: list[str] = []

    # Get text from Name and HelpText which are common properties
    if control.Name:
        listText.append(control.Name)
    if control.HelpText:
        listText.append(control.HelpText)

    # Try to retrieve text using ValuePattern if available
    pattern = cast(
        uiautomation.ValuePattern | None,
        control.GetPattern(uiautomation.PatternId.ValuePattern),
    )
    if pattern is not None and pattern.Value:
        listText.append(pattern.Value)
    else:
        # If ValuePattern is not available or provides no text, check TextPattern
        pattern = cast(
            uiautomation.TextPattern | None,
            control.GetPattern(uiautomation.PatternId.TextPattern),
        )
        if pattern is not None:
            strText = pattern.DocumentRange.GetText(-1)
            if strText:
                listText.append(strText)

    # Recursively process child controls
    for child in control.GetChildren():
        listText.extend(_get_control_text_recursive(control=child))

    return listText


def _get_text(
    selector: SelectorWindow | SelectorUia | SelectorHtml,
    preDelay: int = 300,
    postDelay: int = 200,
) -> tuple[list[str], str]:

    if selector.get("category") == "image":
        raise UiOperationError("Not support getting text by the function, consider using OCR.")

    uiTarget, dictTarget = _UiElement.get_element_with_pre_delay(selector=selector, preDelay=preDelay)

    listText: list[str] = []

    if isinstance(uiTarget, uiautomation.Control):
        listText = _get_control_text_recursive(control=uiTarget)
        delay(postDelay)
        return (listText, "\n".join(listText))
    else:
        # html
        delay(postDelay)
        innerText = dictTarget.get("innerText")
        value = dictTarget.get("value")

        if isinstance(innerText, str) and innerText:
            strTemp = innerText
        elif isinstance(value, str) and value:
            strTemp = value
        else:
            strTemp = ""
        return ([strTemp], strTemp)



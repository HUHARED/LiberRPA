def _set_text(
    selector: SelectorUia | SelectorHtml,
    text: str,
    timeout: int = 10000,
    preDelay: int = 300,
    postDelay: int = 200,
) -> None:

    if selector.get("category") == "image":
        raise UiOperationError("Not support setting text in an image element.")

    if selector.get("category") is None:
        raise UiOperationError("Not support setting text in an UIA window element.")

    if selector.get("category") == "html":
        _UiElement.activate_element_window(selector=selector)

        Chrome_set_element_text(
            htmlSelector=as_selector_html(selector=selector)["specification"],
            text=text,
            clearBeforeWrite=True,
            validateText=False,
            preDelay=preDelay,
            timeout=timeout,
        )

        delay(postDelay)
        return None

    # uia
    uiTarget, _ = _UiElement.get_element_with_pre_delay(selector=selector, preDelay=preDelay)

    if isinstance(uiTarget, uiautomation.Control):
        pattern = cast(
            uiautomation.ValuePattern | None,
            uiTarget.GetPattern(uiautomation.PatternId.ValuePattern),
        )
        if pattern is not None and uiTarget.IsEnabled:
            pattern.SetValue(text)
            delay(postDelay)
            return None

    # Other elements don't support setting text and not be checked before.

    raise UiOperationError(
        f"The element does not support setting text or LiberRPA does not have permission. selector: {selector}"
    )



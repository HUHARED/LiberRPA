def _set_check_state(
    selector: SelectorUia | SelectorHtml,
    checkAction: Literal["checked", "unchecked", "toggle"] = "checked",
    timeout: int = 10000,
    preDelay: int = 300,
    postDelay: int = 200,
) -> None:

    if selector.get("category") == "html":
        _UiElement.activate_element_window(selector=selector)

        # NOTE: Project highlightUI setting will not work for it. (Because the part not only get attributes.)

        Chrome_set_check_state(
            htmlSelector=as_selector_html(selector=selector)["specification"],
            checkAction=checkAction,
            preDelay=preDelay,
            timeout=timeout,
        )
        delay(postDelay)
        return None

    # uia
    uiTarget, _ = _UiElement.get_element_with_pre_delay(selector=selector, preDelay=preDelay)

    if isinstance(uiTarget, uiautomation.Control):
        pattern = cast(
            uiautomation.TogglePattern | None,
            uiTarget.GetPattern(uiautomation.PatternId.TogglePattern),
        )

        if pattern is not None:
            intState: int = pattern.ToggleState
            match checkAction:
                case "checked":
                    if intState == 1:
                        pass
                    elif intState == 0:
                        pattern.Toggle()
                    else:
                        # intState == 2
                        raise ValueError("The element's check state is 'indeterminate', can't be set.")
                case "unchecked":
                    if intState == 0:
                        pass
                    elif intState == 1:
                        pattern.Toggle()
                    else:
                        # intState == 2
                        raise ValueError("The element's check state is 'indeterminate', can't be set.")
                case "toggle":
                    pattern.Toggle()
                case _:
                    raise ValueError(
                        f"The argument checkAction({checkAction}) should be one of {['checked', 'unchecked', 'toggle']}"
                    )

            delay(postDelay)
            return None

    # image or uia element does't support setting check.
    raise UiOperationError(
        f"The element does not support setting check state or LiberRPA does not have permission. selector: {selector}"
    )



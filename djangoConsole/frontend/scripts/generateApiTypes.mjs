// FileName: generateApiTypes.mjs

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const strFrontendPath = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const strSchemaPath = resolve(strFrontendPath, "contracts/browser-api.schema.json");
const strOutputPath = resolve(strFrontendPath, "src/api/generated/browserApi.ts");
const arrArgument = process.argv.slice(2);
if (arrArgument.some((argument) => argument !== "--check")) {
  throw new Error("Usage: node scripts/generateApiTypes.mjs [--check]");
}
const boolCheck = arrArgument.includes("--check");
const dictSchema = JSON.parse(await readFile(strSchemaPath, "utf8"));
// Pydantic's field titles are documentation, not separate TypeScript domain types.
for (const dictDefinition of Object.values(dictSchema.$defs ?? {})) {
  for (const dictProperty of Object.values(dictDefinition.properties ?? {})) {
    delete dictProperty.title;
  }
}
const strExpected = await compile(dictSchema, "BrowserApiContracts", {
  cwd: dirname(strSchemaPath),
  bannerComment:
    "// FileName: browserApi.ts\n\n" +
    "// Generated from frontend/contracts/browser-api.schema.json.\n" +
    "// Run python scripts/export_browser_contracts.py, then npm run generate:contracts in frontend.\n" +
    "// Do not edit this file manually.",
  style: { singleQuote: false, semi: true, tabWidth: 2, printWidth: 92, endOfLine: "lf" },
  // The schema is self-contained; generation never resolves network or filesystem references.
  $refOptions: { resolve: { external: false } },
});
if (boolCheck) {
  let strCurrent = "";
  try {
    strCurrent = await readFile(strOutputPath, "utf8");
  } catch (e) {
    if (e.code !== "ENOENT") throw e;
  }
  if (strCurrent.replaceAll("\r\n", "\n") !== strExpected.replaceAll("\r\n", "\n")) {
    throw new Error(
      "Browser API types are out of date. Run npm run generate:contracts in frontend.",
    );
  }
  console.log("Browser API types match the committed schema.");
} else {
  await mkdir(dirname(strOutputPath), { recursive: true });
  await writeFile(strOutputPath, strExpected, "utf8");
  console.log("Browser API TypeScript types generated from the committed schema.");
}

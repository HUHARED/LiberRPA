// FileName: generateApiTypes.mjs

import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isDeepStrictEqual } from "node:util";

import { compile } from "json-schema-to-typescript";

const strFrontendPath = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// The Python entry point sends the backend schema and shared constants through standard input.
process.stdin.setEncoding("utf8");
let strInput = "";
for await (const strChunk of process.stdin) strInput += strChunk;
const dictInput = JSON.parse(strInput);
const dictSchema = dictInput.schema;
const dictDefinitions = dictSchema.$defs ?? {};
const dictJsonValueInput = dictDefinitions["JsonValue-Input"];
const dictJsonValueOutput = dictDefinitions["JsonValue-Output"];
const boolMergeJsonValue = Boolean(dictJsonValueInput && dictJsonValueOutput);
// Pydantic's field titles are documentation, not separate TypeScript domain types.
for (const dictDefinition of Object.values(dictDefinitions)) {
  for (const dictProperty of Object.values(dictDefinition.properties ?? {})) {
    delete dictProperty.title;
  }
}
function normalizeSchemas(schema) {
  if (!schema || typeof schema !== "object") return;
  if (Array.isArray(schema)) {
    for (const child of schema) normalizeSchemas(child);
    return;
  }
  // Both modes describe the same recursive JSON value; normalize their self-references.
  if (
    boolMergeJsonValue &&
    ["#/$defs/JsonValue-Input", "#/$defs/JsonValue-Output"].includes(schema.$ref)
  ) {
    schema.$ref = "#/$defs/JsonValue";
  }
  // The converter uses the earlier tuple spelling; Pydantic emits draft 2020-12 prefixItems.
  if (Array.isArray(schema.prefixItems)) {
    schema.items = schema.prefixItems;
    delete schema.prefixItems;
    schema.additionalItems = false;
  }
  for (const child of Object.values(schema)) normalizeSchemas(child);
}
normalizeSchemas(dictSchema);
if (boolMergeJsonValue) {
  if (!isDeepStrictEqual(dictJsonValueInput, dictJsonValueOutput)) {
    throw new Error(
      "JsonValue input and output schemas differ; review them before merging.",
    );
  }
  dictDefinitions.JsonValue = dictJsonValueInput;
  delete dictDefinitions["JsonValue-Input"];
  delete dictDefinitions["JsonValue-Output"];
}
const strTypes = await compile(dictSchema, "BrowserApiContracts", {
  cwd: strFrontendPath,
  bannerComment:
    "// FileName: browserApi.ts\n\n" +
    "// Generated from backend browser API contracts.\n" +
    "// Run python scripts/generate_browser_contracts.py to update this file.\n" +
    "// Do not edit this file manually.",
  style: {
    singleQuote: false,
    semi: true,
    tabWidth: 2,
    printWidth: 92,
    trailingComma: "all",
    endOfLine: "lf",
  },
  // The schema is self-contained; generation never resolves network or filesystem references.
  $refOptions: { resolve: { external: false } },
});
const dictRunSettingProperty = dictDefinitions.RunSettings.properties;
const arrConstant = [
  `export const INT_LIST_PAGE_SIZE = ${dictInput.list_page_size};`,
  `export const INT_MAX_RUN_STATISTICS_DAYS = ${dictInput.max_run_statistics_days};`,
  `export const INT_ORGANIZATION_SERVICE_REASON_MAX_LENGTH = ${dictInput.max_organization_service_reason_length};`,
  `export const INT_MAX_RETRY_COUNT = ${dictRunSettingProperty.max_retry_count.maximum};`,
  `export const INT_MAX_TIMEOUT_MIN = ${dictRunSettingProperty.timeout_min.maximum};`,
];
for (const [strConstantName, strEnumName] of [
  ["ARR_CONFLICT_POLICY", "RunConflictPolicy"],
  ["ARR_PRIORITY", "RunPriority"],
  ["ARR_LOG_LEVEL", "RunLogLevel"],
  ["ARR_ASSET_TYPE_VALUE", "AssetType"],
  ["ARR_ORDINARY_ASSET_TYPE", "OrdinaryAssetType"],
  ["ARR_ASSET_REFERENCE_KIND", "AssetReferenceKind"],
  ["ARR_QUEUE_ITEM_STATUS", "QueueItemStatus"],
  ["ARR_QUEUE_ITEM_FILTER_STATUS", "QueueItemFilterStatus"],
  ["ARR_QUEUE_ITEM_ORDER", "QueueItemOrder"],
  ["ARR_EXECUTOR_ASSOCIATION_STATUS", "ExecutorAssociationStatus"],
  ["ARR_JOB_SOURCE", "JobSource"],
  ["ARR_FILE_UPLOAD_STATE", "UploadState"],
  ["ARR_AUDIT_ACTION", "AuditAction"],
  ["ARR_AUDIT_CHANNEL", "AuditChannel"],
  ["ARR_AUDIT_RESULT_VALUE", "AuditResult"],
  ["ARR_AUDIT_STAGE", "AuditStage"],
  ["ARR_DEPARTMENT_ROLE", "DepartmentRole"],
  ["ARR_INVITATION_STATUS", "InvitationStatus"],
  ["ARR_DEPARTMENT_DELETION_BLOCKER_CODE", "DepartmentDeletionBlockerCode"],
  ["ARR_API_KEY_STATUS", "ApiKeyStatus"],
  ["ARR_EMAIL_STATUS", "EmailStatus"],
  ["ARR_EMAIL_REASON_CODE", "EmailReasonCode"],
  ["ARR_ORGANIZATION_LIMIT", "OrganizationLimit"],
  ["ARR_LIMIT_UNIT", "LimitUnit"],
  ["ARR_PLATFORM_ORGANIZATION_STATUS", "PlatformOrganizationStatus"],
]) {
  const strEnumValue = dictDefinitions[strEnumName].enum
    .map((value) => `  ${JSON.stringify(value)},`)
    .join("\n");
  arrConstant.push(
    `export const ${strConstantName} = [\n${strEnumValue}\n] as const satisfies readonly ${strEnumName}[];`,
  );
}
const strAuditActionLabel = dictInput.audit_actions
  .map(([value, label]) => `  ${JSON.stringify(value)}: ${JSON.stringify(label)},`)
  .join("\n");
arrConstant.push(
  `export const AUDIT_ACTION_LABEL = {\n${strAuditActionLabel}\n} as const satisfies Record<AuditAction, string>;`,
);
for (const strEnumName of [
  "DepartmentRole",
  "RunEmailRecipientStatus",
  "PackageReferenceKind",
  "PackagePreparationState",
  "PackageUploadState",
  "JobTargetType",
  "JobState",
  "RunStatus",
  "RunEventKind",
  "OutputsStatus",
  "RecordingStatus",
  "RunFileKind",
  "BrowserMessageType",
  "OrganizationLimit",
  "LimitUnit",
  "PlatformOrganizationStatus",
]) {
  const strMember = dictDefinitions[strEnumName].enum
    .map((value) => {
      const strName = value
        .split("_")
        .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
        .join("");
      return `  ${strName}: ${JSON.stringify(value)},`;
    })
    .join("\n");
  arrConstant.push(
    `export const ${strEnumName} = {\n${strMember}\n} as const satisfies Record<string, ${strEnumName}>;`,
  );
}
process.stdout.write(`${strTypes}\n${arrConstant.join("\n")}\n`);

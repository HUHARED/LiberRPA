export function getRiskyPyModuleNameReason(pyFile: string): string | null {
  let strNormalizedPath = pyFile.trim();

  if (strNormalizedPath.startsWith("./")) {
    strNormalizedPath = strNormalizedPath.slice(2);
  }

  const arrPathParts = strNormalizedPath.split("/");

  if (arrPathParts.length === 0 || arrPathParts[0] === "") {
    return null;
  }

  const strTopLevelName = arrPathParts[0].replace(/\.py$/i, "").toLowerCase();
  const strFileName = arrPathParts[arrPathParts.length - 1]
    .replace(/\.py$/i, "")
    .toLowerCase();

  if (SET_RESERVED_PACKAGE_NAMES.has(strTopLevelName)) {
    return `Python file path uses reserved top-level package name "${strTopLevelName}".`;
  }

  if (SET_RESERVED_PACKAGE_NAMES.has(strFileName)) {
    return `Python file name uses reserved package name "${strFileName}".`;
  }

  if (SET_LIBERRPA_EXPORTED_NAMES.has(strTopLevelName)) {
    return `Python file path uses a top-level name that conflicts with a LiberRPA command/module name "${strTopLevelName}".`;
  }

  if (SET_LIBERRPA_EXPORTED_NAMES.has(strFileName)) {
    return `Python file name conflicts with a LiberRPA command/module name "${strFileName}".`;
  }

  if (SET_PYTHON_STDLIB_MODULE_NAMES.has(strTopLevelName)) {
    return `Python file path may shadow Python standard library module "${strTopLevelName}".`;
  }

  if (SET_PYTHON_STDLIB_MODULE_NAMES.has(strFileName)) {
    return `Python file name may shadow Python standard library module "${strFileName}".`;
  }

  if (SET_LIBERRPA_THIRD_PARTY_MODULE_NAMES.has(strTopLevelName)) {
    return `Python file path may shadow a third-party package used by LiberRPA "${strTopLevelName}".`;
  }

  if (SET_LIBERRPA_THIRD_PARTY_MODULE_NAMES.has(strFileName)) {
    return `Python file name may shadow a third-party package used by LiberRPA "${strFileName}".`;
  }

  return null;
}
